"""C2PA (Content Credentials) manifest verification -- Branch D's
highest-precision evidence lane per the blueprint: a valid signed
manifest is stronger evidence of provenance than any pixel analysis,
and its absence is neutral (most real-world images have none yet, per
the 2026 adoption survey cited in the blueprint), never treated as
suspicious on its own.

Uses the `c2pa-python` bindings when installed; degrades to a documented
"unavailable" status otherwise so the pipeline never silently pretends
to have checked a manifest it couldn't actually verify.
"""
from __future__ import annotations
from dataclasses import dataclass, field
from enum import Enum

try:
    import c2pa as _c2pa
    _HAS_C2PA = True
except Exception:  # pragma: no cover - optional dependency
    _HAS_C2PA = False


class C2PAStatus(str, Enum):
    UNAVAILABLE = "unavailable"   # verifier not installed -- distinct from ABSENT
    ABSENT = "absent"             # verifier ran, no manifest found
    INVALID = "invalid"           # manifest present but signature/hash failed
    VALID = "valid"


STATUS_TO_FEATURE = {
    C2PAStatus.UNAVAILABLE: 0.0,
    C2PAStatus.ABSENT: 0.0,
    C2PAStatus.INVALID: 1.0,
    C2PAStatus.VALID: 2.0,
}


@dataclass
class C2PAReport:
    status: C2PAStatus
    claim_generator: str | None = None
    assertions: list[str] = field(default_factory=list)
    signature_issuer: str | None = None
    detail: str = ""


def verify_manifest(image_path: str) -> C2PAReport:
    if not _HAS_C2PA:
        return C2PAReport(
            status=C2PAStatus.UNAVAILABLE,
            detail="c2pa-python is not installed; provenance credentials "
                   "were not checked. Install `c2pa-python` to enable this "
                   "evidence lane.",
        )

    try:
        reader = _c2pa.Reader(image_path)
    except Exception as e:
        # No manifest store, or the file isn't a supported container --
        # this is the common/expected case for most images today.
        return C2PAReport(status=C2PAStatus.ABSENT,
                           detail=f"No C2PA manifest found ({e}).")

    try:
        manifest_json = reader.json()
        import json
        manifest = json.loads(manifest_json)
    except Exception as e:
        return C2PAReport(status=C2PAStatus.INVALID,
                           detail=f"Manifest present but could not be parsed: {e}")

    active = manifest.get("active_manifest")
    manifests = manifest.get("manifests", {})
    active_manifest = manifests.get(active, {}) if active else {}

    validation_status = manifest.get("validation_status", [])
    has_error = any(v.get("code", "").endswith("error") for v in validation_status)
    if has_error:
        return C2PAReport(
            status=C2PAStatus.INVALID,
            claim_generator=active_manifest.get("claim_generator"),
            detail=f"Signature/hash validation failed: {validation_status}",
        )

    assertions = [a.get("label", "") for a in active_manifest.get("assertions", [])]
    signature_info = active_manifest.get("signature_info", {})

    return C2PAReport(
        status=C2PAStatus.VALID,
        claim_generator=active_manifest.get("claim_generator"),
        assertions=assertions,
        signature_issuer=signature_info.get("issuer"),
        detail="Manifest signature and content hash verified.",
    )


def to_evidence_finding(report: C2PAReport) -> dict:
    """Maps a C2PAReport to the same {branch, finding, weight} shape used
    throughout forgelens/inference/pipeline.py, so it can be appended to
    the evidence list identically to every other branch."""
    if report.status == C2PAStatus.VALID:
        gen = report.claim_generator or "an unspecified tool"
        assertions_str = ", ".join(report.assertions) if report.assertions else "none recorded"
        finding = (f"Valid C2PA content credential found, generated by {gen}. "
                   f"Assertions: {assertions_str}.")
        weight = "high"
    elif report.status == C2PAStatus.INVALID:
        finding = f"A C2PA manifest is present but failed verification: {report.detail}"
        weight = "high"
    elif report.status == C2PAStatus.ABSENT:
        finding = "No C2PA content credential present (common for most images today; not itself evidence of manipulation)."
        weight = "neutral"
    else:
        finding = "C2PA verification unavailable in this deployment."
        weight = "neutral"
    return {"branch": "c2pa", "finding": finding, "weight": weight,
            "detail": {"status": report.status.value}}
